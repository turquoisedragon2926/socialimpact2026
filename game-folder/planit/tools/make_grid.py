"""Builds planIt's map from a backend baseline, so every planIt tile is one backend cell.

Land cover comes from the baseline (the dominant ESA WorldCover class in each cell).
Terrain height, building style and height, and the visual variant are looked up from
the original 145 m planIt map at each cell's center; they only affect how tiles look.

    uv run python planit/tools/make_grid.py data/sf-2021.json planit/data/san-francisco-data.js planit/data/sf-2021-grid.js
"""
import json
import math
import sys


def read_js(path):
    text = open(path).read()
    return json.loads(text[text.index('{'):text.rindex('}') + 1])


def main(baseline_path, look_path, out_path):
    baseline = json.load(open(baseline_path))
    look = read_js(look_path)
    cells = baseline['cells']
    pos = [tuple(map(int, c['id'].split(':'))) for c in cells]
    south_rows = max(r for r, _ in pos) + 1
    cols = max(c for _, c in pos) + 1
    rows = south_rows
    n = rows * cols

    # Backend rows count up from the south; planIt rows count down from the north.
    index = {cell['id']: (rows - 1 - r) * cols + c for cell, (r, c) in zip(cells, pos)}

    # Fit lat/lon of tile centers to row/col (the backend grid is in UTM meters,
    # which is close to a lat/lon grid over one city).
    def fit(xs, ys):
        mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
        slope = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
        return my - slope * mx, slope
    centered = [(index[c['id']], c['center']) for c in cells]
    lon0, dlon = fit([i % cols for i, _ in centered], [lon for _, (lon, _) in centered])
    lat0, dlat = fit([i // cols for i, _ in centered], [lat for _, (_, lat) in centered])
    west, north = lon0 - dlon / 2, lat0 - dlat / 2
    east, south = west + dlon * cols, north + dlat * rows
    tile_m = baseline['cell_m']

    # Old map lookup by lat/lon (same formula as landmarks.js geoToTile).
    lw, _, _, ln = look['bbox']
    mid = (look['bbox'][1] + look['bbox'][3]) / 2
    ldlat = look['tileMeters'] / 111320
    ldlon = look['tileMeters'] / (111320 * math.cos(math.radians(mid)))

    def old_index(lat, lon):
        r, c = int((ln - lat) / ldlat), int((lon - lw) / ldlon)
        if 0 <= r < look['rows'] and 0 <= c < look['cols']:
            return r * look['cols'] + c
        return None

    out = {'name': baseline['name'], 'bbox': [west, south, east, north], 'tileMeters': tile_m,
           'stepMeters': look['stepMeters'], 'rows': rows, 'cols': cols,
           'baselineId': baseline['id'], 'baselineYear': baseline['year'],
           'ids': [None] * n, 'codes': [0] * n, 'levels': [0] * n, 'variants': [0] * n,
           'styles': [None] * n, 'heights': [0] * n}
    for cell in cells:
        i = index[cell['id']]
        if not cell['fractions'] or not cell['source_classes']:
            continue
        code = int(max(cell['source_classes'], key=cell['source_classes'].get))
        lon, lat = cell['center']
        j = old_index(lat, lon)
        out['ids'][i] = cell['id']
        out['codes'][i] = code
        out['variants'][i] = look['variants'][j] if j is not None else (i * 7) % 8
        if j is not None:
            out['levels'][i] = look['levels'][j]
            if code == 50:
                out['styles'][i] = look['styles'][j]
                out['heights'][i] = look['heights'][j]
    header = ('// sf-2021-grid.js (generated by tools/make_grid.py; do not edit by hand)\n'
              f'// One tile per backend cell of baseline {baseline["id"][:12]} ({baseline["name"]} {baseline["year"]}, {tile_m:g} m).\n'
              '// ids: backend cell id per tile ("row:col", rows from the south), null = no cell.\n'
              '// codes: dominant ESA WorldCover class. levels/styles/heights/variants: looks only,\n'
              '// sampled from the original 145 m planIt map.\n')
    with open(out_path, 'w') as f:
        f.write(header + 'export default ' + json.dumps(out, separators=(',', ':')) + ';\n')
    print(f'{rows}x{cols} tiles, {sum(1 for x in out["ids"] if x)} cells -> {out_path}')


if __name__ == '__main__':
    main(*sys.argv[1:4])
